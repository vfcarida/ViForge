@pytest.mark.unit
def test_code_quality_filter():
    filter_fn = CodeQualityFilter(min_length=50, max_length=1000)

    # 1. Valid code
    valid_code = {
        "text": (
            "def calculate_area(width: float, height: float) -> float:\n"
            '    """Calculate rectangle area."""\n'
            "    return width * height\n"
        )
    }
    assert filter_fn(valid_code) is True

    # 2. Too short
    too_short = {"text": "def x(): pass\n"}
    assert filter_fn(too_short) is False

    # 3. Auto-generated boilerplate
    autogen_code = {
        "text": (
            "# <auto-generated>\n# This code was generated by a tool.\n# Do not edit\n"
            "def autogen(): return 1\n"
        )
    }
    assert filter_fn(autogen_code) is False

    # 4. Minified code (single long line)
    minified_code = {"text": "var a=1;var b=2;" + "var c=3;var d=4;var e=5;" * 50}
    assert filter_fn(minified_code) is False


@pytest.mark.unit
def test_sft_format_conversion(tmp_path: Path):
    raw_data = [
        {
            "instruction": "Write a python function to add two numbers.",
            "input": "Integers a and b",
            "output": "def add(a: int, b: int) -> int:\n    return a + b\n",
        },
        {
            "instruction": "Explain recursion in python.",
            "output": "Recursion is when a function calls itself directly or indirectly.",
        },
    ]
    raw_file = tmp_path / "raw_sft.jsonl"
    with open(raw_file, "w", encoding="utf-8") as f:
        for r in raw_data:
            f.write(json.dumps(r) + "\n")

    cfg = DatasetConfig(
        domain="software_engineering",
        source=str(raw_file),
        format="sft",
        min_length=10,
    )
    preparer = DatasetPreparer(cfg)
    prepared = preparer.prepare()

    assert len(prepared) == 2
    for rec in prepared:
        assert "messages" in rec
        assert len(rec["messages"]) == 2
        assert rec["messages"][0]["role"] == "user"
        assert rec["messages"][1]["role"] == "assistant"
    assert any("Integers a and b" in rec["messages"][0]["content"] for rec in prepared)


@pytest.mark.unit
def test_dpo_and_grpo_format_conversion(tmp_path: Path):
    # DPO
    dpo_raw = [
        {
            "prompt": "How do I reverse a list in Python?",
            "chosen": "You can use `lst.reverse()` or `lst[::-1]`.",
            "rejected": "You cannot reverse a list in Python.",
        }
    ]
    dpo_file = tmp_path / "raw_dpo.jsonl"
    dpo_file.write_text(json.dumps(dpo_raw[0]) + "\n", encoding="utf-8")

    cfg_dpo = DatasetConfig(
        domain="software_engineering",
        source=str(dpo_file),
        format="dpo",
        min_length=10,
    )
    dpo_out = DatasetPreparer(cfg_dpo).prepare()
    assert len(dpo_out) == 1
    assert "prompt" in dpo_out[0]
    assert "chosen" in dpo_out[0]
    assert "rejected" in dpo_out[0]

    # GRPO
    cfg_grpo = DatasetConfig(
        domain="software_engineering",
        source=str(dpo_file),
        format="grpo",
        min_length=10,
    )
    grpo_out = DatasetPreparer(cfg_grpo).prepare()
    assert len(grpo_out) == 1
    assert "prompt" in grpo_out[0]
    assert "chosen" not in grpo_out[0]


@pytest.mark.unit
def test_cpt_format_conversion_and_deduplication(tmp_path: Path):
    raw_cpt = [
        {"text": "def foo():\n    return 'Unique text segment 1234567890'\n"},
        {"text": "def foo():\n    return 'Unique text segment 1234567890'\n"},  # exact duplicate
        {"text": "def bar():\n    return 'Different text segment 0987654321'\n"},
    ]
    cpt_file = tmp_path / "raw_cpt.jsonl"
    with open(cpt_file, "w", encoding="utf-8") as f:
        for r in raw_cpt:
            f.write(json.dumps(r) + "\n")

    cfg_cpt = DatasetConfig(
        domain="software_engineering",
        source=str(cpt_file),
        format="cpt",
        min_length=10,
        dedup=True,
    )
    cpt_out = DatasetPreparer(cfg_cpt).prepare()
    assert len(cpt_out) == 2
    assert all("text" in r for r in cpt_out)


