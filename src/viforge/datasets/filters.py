"""
ViForge Dataset Quality Filters and Sanitizers.
Provides domain-aware quality filtering for code and natural language text.
"""

from abc import ABC, abstractmethod
from typing import Any, Dict, Optional


class BaseQualityFilter(ABC):
    """Abstract base class for dataset quality filters."""

    @abstractmethod
    def __call__(self, example: Dict[str, Any]) -> bool:
        """Return True if example passes quality heuristics, False otherwise."""
        pass


class CodeQualityFilter(BaseQualityFilter):
    """
    Quality filter tailored for source code repositories and instruction-tuning datasets.
    Filters minified code, auto-generated boilerplate, and length outliers.
    """

    BLOCKED_PATTERNS = [
        "auto-generated",
        "<auto-generated>",
        "generated by",
        "do not edit",
        "this file is generated",
        "automatically generated",
    ]

    def __init__(
        self,
        min_length: int = 50,
        max_length: int = 32000,
        max_avg_line_length: float = 200.0,
        max_single_line_length: int = 1000,
        text_column: str = "text",
    ):
        self.min_length = min_length
        self.max_length = max_length
        self.max_avg_line_length = max_avg_line_length
        self.max_single_line_length = max_single_line_length
        self.text_column = text_column

    @staticmethod
    def _avg_line_length(text: str) -> float:
        lines = [line for line in text.splitlines() if line.strip()]
        if not lines:
            return 0.0
        return sum(len(line) for line in lines) / len(lines)

    def _extract_text(self, example: Dict[str, Any]) -> str:
        if self.text_column in example and example[self.text_column]:
            return str(example[self.text_column])

        # Fallback to common instruction/content fields
        for key in ["content", "code", "instruction", "prompt", "messages"]:
            val = example.get(key)
            if isinstance(val, str) and val.strip():
                return val
            if isinstance(val, list):
                # Concatenate message contents
                texts = [str(msg.get("content", "")) for msg in val if isinstance(msg, dict)]
                return "\n".join(texts)
        return ""

    def __call__(self, example: Dict[str, Any]) -> bool:
        text = self._extract_text(example)
        if not text or not text.strip():
            return False

        # 1. Length bounds check
        if len(text) < self.min_length or len(text) > self.max_length:
            return False

        # 2. Auto-generated boilerplate check (in first 200 chars)
        header = text[:200].lower()
        if any(pat in header for pat in self.BLOCKED_PATTERNS):
            return False

        # 3. Minified code detection (line length checks)
        lines = text.splitlines()
        if lines:
            if self._avg_line_length(text) > self.max_avg_line_length:
                return False
            if any(len(line) > self.max_single_line_length for line in lines):
                return False

        return True


class TextQualityFilter(BaseQualityFilter):
    """General text length and quality heuristic filter."""

    def __init__(
        self,
        min_length: int = 50,
        max_length: int = 32000,
        text_column: str = "text",
    ):
        self.min_length = min_length
        self.max_length = max_length
        self.text_column = text_column

    def __call__(self, example: Dict[str, Any]) -> bool:
        text = str(example.get(self.text_column, ""))
        if not text or not text.strip():
            return False
        return self.min_length <= len(text) <= self.max_length
